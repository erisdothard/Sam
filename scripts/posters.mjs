/* Video posters. YouTube's own 1080x1920 poster for each Short (cached in assets-src/yt/, git-ignored)
   -> public/video/<id>.webp at 720x1280, plus a 16px blur for the loading state.
   Fetch a missing poster:  curl -o assets-src/yt/yt_<id>_oardefault.jpg https://i.ytimg.com/vi/<id>/oardefault.jpg
     node scripts/posters.mjs                                                                   */
import { readFile, writeFile, mkdir, access } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(import.meta.dirname, '..');
const src = (id) => path.join(root, 'assets-src/yt', `yt_${id}_oardefault.jpg`);
const out = path.join(root, 'public/video');
await mkdir(out, { recursive: true });

const ids = [...(await readFile(path.join(root, 'src/content/videos.ts'), 'utf8')).matchAll(/id: '([\w-]{11})'/g)].map((m) => m[1]);
const blurs = {};
for (const id of ids) {
  const file = src(id);
  if (!(await access(file).then(() => true, () => false))) {
    const res = await fetch(`https://i.ytimg.com/vi/${id}/oardefault.jpg`);
    if (!res.ok) throw new Error(`${id}: poster HTTP ${res.status}`);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, Buffer.from(await res.arrayBuffer()));
  }
  const img = sharp(file).resize(720, 1280, { fit: 'cover' });
  const { size } = await img.clone().webp({ quality: 78 }).toFile(path.join(out, `${id}.webp`));
  const blur = await sharp(file).resize(9, 16).jpeg({ quality: 50 }).toBuffer();
  blurs[id] = `data:image/jpeg;base64,${blur.toString('base64')}`;
  console.log(`${id}  720x1280  ${(size / 1024).toFixed(0)} KB`);
}
await writeFile(
  path.join(root, 'src/content/posters.ts'),
  `// Generated by scripts/posters.mjs. Do not edit by hand.\nexport const posterBlur: Record<string, string> = ${JSON.stringify(blurs, null, 2)};\n`,
);
